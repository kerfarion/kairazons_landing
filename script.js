function initVanillaCarousel(containerId, autoInterval = 2000, isCentered = false) {
    const container = document.getElementById(containerId);
    if (!container) return;
    const track = container.querySelector('.custom-carousel-track');
    if (!track) return;

    const originalItems = Array.from(track.children);
    if (originalItems.length === 0) return;

    // Размножаем элементы (5 наборов), чтобы заполнить любой экран с запасом
    track.innerHTML = '';
    for (let i = 0; i < 5; i++) {
        originalItems.forEach(item => {
            track.appendChild(item.cloneNode(true));
        });
    }

    let isAnimating = false;
    // Оставляем один полный оригинальный набор (например, 3 слова) слева вне экрана, 
    // чтобы карусели было откуда выезжать, а сами начинаем ровно со второго набора
    const ACTIVE_INDEX = originalItems.length; 

    function updatePosition(smooth = false) {
        const activeItem = track.children[ACTIVE_INDEX];
        let offset = 0;

        if (isCentered) {
            // Математически вычисляем центр окна и сдвигаем активный элемент ровно в него
            const containerCenter = container.clientWidth / 2;
            const itemCenter = activeItem.offsetLeft + (activeItem.offsetWidth / 2);
            offset = itemCenter - containerCenter;
        } else {
            // Обычное выравнивание по левому краю (идеально для сетки логотипов)
            offset = activeItem.offsetLeft;
        }

        track.style.transition = smooth ? 'transform 0.6s cubic-bezier(0.25, 0.46, 0.45, 0.94)' : 'none';
        track.style.transform = `translateX(-${offset}px)`;
    }

    // Даем браузеру долю секунды на отрисовку шрифтов, затем выравниваем
    setTimeout(() => updatePosition(false), 50);

    // При изменении ширины экрана пересчитываем центрирование
    window.addEventListener('resize', () => {
        if (!isAnimating) updatePosition(false);
    });

    function nextSlide() {
        if (isAnimating || document.hidden) return; // document.hidden спасает от сбивания таймеров в свернутых вкладках
        isAnimating = true;

        const nextItem = track.children[ACTIVE_INDEX + 1];
        let targetOffset = 0;

        if (isCentered) {
            const containerCenter = container.clientWidth / 2;
            const nextItemCenter = nextItem.offsetLeft + (nextItem.offsetWidth / 2);
            targetOffset = nextItemCenter - containerCenter;
        } else {
            targetOffset = nextItem.offsetLeft;
        }

        track.style.transition = 'transform 0.6s cubic-bezier(0.25, 0.46, 0.45, 0.94)';
        track.style.transform = `translateX(-${targetOffset}px)`;

        // После завершения анимации перекидываем первый элемент в конец для бесконечности
        setTimeout(() => {
            track.appendChild(track.firstElementChild);
            // Незаметно пересчитываем позицию (потому что все элементы сместились на 1 шаг влево в DOM)
            updatePosition(false);
            void track.offsetWidth;
            isAnimating = false;
        }, 600);
    }

    setInterval(nextSlide, autoInterval);
}

